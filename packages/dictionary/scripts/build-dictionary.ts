const CONTRACTION_BOOST = 10_000_000;
// Score for contractions lacking SUBTLEX frequency data (nearly all of them —
// the corpus underrepresents apostrophe forms). Treated as a moderately common
// word (~freq 50k) so a contraction still outranks its rare homophones ("its",
// "wont", "whats") but loses to a genuinely common one (e.g. "there" ~221k beats
// "they're"). Mirrors UNKNOWN_CONTRACTION_SCORE in src/frequency.ts.
const UNKNOWN_CONTRACTION_SCORE = 50_000;
const NUMERIC_REGEX = /[0-9]/;

/**
 * Score a word for sorting (higher = more common, should come first).
 */
export function getWordScore(word: string, freqMap: Map<string, number>): number {
  const freq = freqMap.get(word.toLowerCase()) ?? 0;
  const isContraction = COMMON_CONTRACTIONS.has(word.toLowerCase());

  if (freq > 0) {
    return isContraction ? freq + CONTRACTION_BOOST : freq;
  }

  if (isContraction) {
    return UNKNOWN_CONTRACTION_SCORE;
  }

  if (NUMERIC_REGEX.test(word)) {
    return -1_000_000 - word.length;
  }

  return -word.length;
}

/**
 * Generates the reverse dictionary: phoneme key -> words (sorted by frequency).
 */
async function generateReverseDictionary(dict: CMUDictionary): Promise<void> {
  console.log('Generating reverse dictionary...');

  const freqMap = buildFrequencyMap();

  // Build reverse mapping: phoneme key -> words
  const reverseDict: Record<string, string[]> = {};

  for (const [word, phonemes] of Object.entries(dict)) {
    // Strip stress markers and join to create key
    const phonemeKey = phonemes.map(stripStress).join(' ');

    if (!reverseDict[phonemeKey]) {
      reverseDict[phonemeKey] = [];
    }
    reverseDict[phonemeKey].push(word);
  }

  // Sort each word list by score (highest first = most common)
  for (const key of Object.keys(reverseDict)) {
    reverseDict[key].sort((a, b) => {
      return getWordScore(b, freqMap) - getWordScore(a, freqMap);
    });
  }

  const keyCount = Object.keys(reverseDict).length;
  console.log(`Reverse dictionary: ${keyCount} phoneme keys`);

  await writeDualOutput(
    REVERSE_OUTPUT_PATH,
    reverseDict,
    'reverseCmudict',
    'Auto-generated reverse CMU dictionary - do not edit'
  );
}

/**
 * Generates en.json for the website: CMU dict + custom words merged.
 * Custom pronunciations override CMU entries.
 */
async function generateEnJson(dict: CMUDictionary): Promise<void> {
  console.log('Generating en.json (CMU + custom words merged)...');
  const merged = { ...dict };
  let overrides = 0;
  let additions = 0;
  for (const [word, phonemes] of Object.entries(CUSTOM_PRONUNCIATIONS)) {
    if (word in merged) {
      overrides++;
    } else {
      additions++;
    }
    merged[word] = phonemes;
  }
  const json = JSON.stringify(merged);
  await fs.mkdir(path.dirname(EN_JSON_PATH), { recursive: true });
  await fs.writeFile(EN_JSON_PATH, json, 'utf8');
  console.log(
    `  en.json: ${Object.keys(merged).length} entries (${overrides} overrides, ${additions} additions), ${(json.length / 1024 / 1024).toFixed(1)} MB`
  );
}

